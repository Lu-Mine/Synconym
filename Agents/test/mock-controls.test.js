import test from 'node:test';
import assert from 'node:assert/strict';
import { RoomManager } from '../../server/rooms.js';
import { createMockControls } from '../../server/mock.js';

test('模拟全局暂停、阶段导航和恢复保持倒计时', t => {
  t.mock.timers.enable({ apis: ['Date'], now: 100000 });
  const manager = new RoomManager();
  const controls = createMockControls(manager);
  t.after(() => manager.close());
  const a = manager.connect();
  a.ws = { readyState: 1, send() {}, close() {} };
  const send = message => { a.lastWrite = 0; manager.handle(a, message); };
  const act = (action, extra = {}) => controls.handle(a, { action, ...extra });
  act('pause');
  send({ type: 'createRoom' });
  const room = manager.roomFor(a);
  act('add');
  const bot = room.players.find(p => p.uid !== a.uid);
  act('ready', { uid: bot.uid, ready: true });
  send({ type: 'start' });
  assert.equal(room.phase, 'countdown');
  const first = controls.annotate({ type: 'state', room: { code: room.code, players: [], phaseDeadline: room.phaseDeadline } });
  assert.equal(first.mockPausedAt, 100000);
  assert.equal(first.room.phaseDeadline - first.mockPausedAt, 5000);
  t.mock.timers.tick(12000);
  act('advance');
  assert.equal(room.phase, 'writing');
  const writing = controls.annotate({ type: 'state', room: { code: room.code, players: [], phaseDeadline: room.phaseDeadline } });
  assert.equal(writing.room.phaseDeadline - writing.mockPausedAt, room.writeSeconds * 1000);
  assert.equal(writing.room.mockCanBack, true);
  act('back');
  assert.equal(room.phase, 'countdown');
  let view = controls.annotate({ type: 'state', room: { code: room.code, players: [], phaseDeadline: room.phaseDeadline } });
  assert.equal(view.room.mockCanForward, true);
  assert.equal(view.room.phaseDeadline - view.mockPausedAt, 5000);
  act('advance');
  assert.equal(room.phase, 'writing');
  t.mock.timers.tick(90000);
  act('resume');
  assert.equal(room.phase, 'writing');
  assert.equal(room.phaseDeadline - Date.now(), room.writeSeconds * 1000);
  assert.equal(controls.annotate({ type: 'state', room: null }).mockPausedAt, null);
});

test('回退后新的游戏操作清除未来阶段', t => {
  t.mock.timers.enable({ apis: ['Date'], now: 100000 });
  const manager = new RoomManager(); const controls = createMockControls(manager);
  t.after(() => manager.close());
  const a = manager.connect(); a.ws = { readyState: 1, send() {}, close() {} };
  const send = message => { a.lastWrite = 0; manager.handle(a, message); };
  send({ type: 'createRoom' }); const room = manager.roomFor(a);
  controls.handle(a, { action: 'add' });
  const bot = room.players.find(p => p.uid !== a.uid);
  controls.handle(a, { action: 'ready', uid: bot.uid, ready: true });
  send({ type: 'start' }); controls.handle(a, { action: 'advance' });
  controls.handle(a, { action: 'back' });
  assert.equal(room.phase, 'countdown');
  controls.handle(a, { action: 'advance' });
  send({ type: 'submitWord', word: '苹果' });
  controls.handle(a, { action: 'submitWord', uid: bot.uid, word: '香蕉' });
  assert.equal(room.phase, 'voting');
  controls.handle(a, { action: 'back' });
  controls.handle(a, { action: 'submitWord', uid: bot.uid, word: '梨' });
  const view = controls.annotate({ type: 'state', room: { code: room.code, players: [] } });
  assert.equal(view.room.mockCanForward, false);
});
